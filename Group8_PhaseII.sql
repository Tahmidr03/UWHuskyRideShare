/* ****************************************************
   PART C — Designing SQL Queries
   **************************************************** */

/* SQL Query 1 — 3+ table join
 Purpose: Show each confirmed ride with driver & rider names, start/end zones, and start time.
 Expected: One row per confirmed match; columns: driver, rider, zones, time, status.
*/
SELECT d.full_name AS driver_name,
       r.full_name AS rider_name,
       o.start_zone,
       o.end_zone,
       o.start_time,
       m.status
FROM Matches m
JOIN RideOffers   o ON m.offer_id   = o.offer_id
JOIN RideRequests q ON m.request_id = q.request_id
JOIN Users d ON o.driver_id = d.user_id
JOIN Users r ON q.rider_id  = r.user_id
WHERE m.status = 'confirmed'
ORDER BY o.start_time;

/* SQL Query 2 — Nested + GROUP BY (top-rated drivers via ALL)
 Purpose: Find driver(s) whose avg rating is ≥ every other driver's avg rating.
 Expected: 1+ rows (ties possible): driver, avg_score.
*/
SELECT u.full_name AS driver_name, AVG(t.score) AS avg_score
FROM Ratings t
JOIN Users   u ON t.ratee_user_id = u.user_id
WHERE u.role IN ('driver','both')
GROUP BY u.user_id, u.full_name
HAVING AVG(t.score) >= ALL (
  SELECT AVG(t2.score)
  FROM Ratings t2
  JOIN Users u2 ON t2.ratee_user_id = u2.user_id
  WHERE u2.role IN ('driver','both')
  GROUP BY u2.user_id
);

/* SQL Query 3 — Correlated subquery 
 Purpose: List offers where matched seats (pending/confirmed) exceed seats_available.
 Expected: 0+ rows: offer_id, driver, seats_available, seats_matched.
*/
SELECT o.offer_id,
       u.full_name AS driver_name,
       o.seats_available,
       (SELECT COUNT(*)
          FROM Matches m
         WHERE m.offer_id = o.offer_id
           AND m.status IN ('pending','confirmed')) AS seats_matched
FROM RideOffers o
JOIN Users u ON o.driver_id = u.user_id
WHERE o.seats_available < (
  SELECT COUNT(*) FROM Matches m
  WHERE m.offer_id = o.offer_id
    AND m.status IN ('pending','confirmed')
);

/* SQL Query 4 — FULL OUTER JOIN (supply vs demand by zone/time)
 Purpose: Compare offers and requests on same date/zone (who's unmatched?).
 Expected: Rows for matched or unmatched items; NULLs indicate no counterpart.
*/
SELECT COALESCE(o.start_zone, q.from_zone) AS zone,
       TRUNC(COALESCE(o.start_time, q.desired_time)) AS ride_day,
       o.offer_id,
       q.request_id
FROM RideOffers o
FULL OUTER JOIN RideRequests q
  ON o.start_zone  = q.from_zone
 AND o.end_zone    = q.to_zone
 AND TRUNC(o.start_time) = TRUNC(q.desired_time)
ORDER BY ride_day, zone;

/* SQL Query 5 — Set operation (people who both offered and requested rides)
 Purpose: Show users who are drivers at least once and also made a request.
 Expected: 0+ rows: user_id, name, email.
*/
SELECT u.user_id, u.full_name, u.uw_email
FROM Users u
WHERE u.user_id IN (
  SELECT driver_id FROM RideOffers
  INTERSECT
  SELECT rider_id FROM RideRequests
);

/* SQL Query 6 — Zone stats (aggregation + HAVING)
 Purpose: Avg seats offered per start_zone for 2025-11-10 to 2025-11-12, zones with ≥2 offers.
 Expected: zone, offers_count, avg_seats.
*/
SELECT o.start_zone,
       COUNT(*) AS offers_count,
       ROUND(AVG(o.seats_available), 2) AS avg_seats
FROM RideOffers o
WHERE TRUNC(o.start_time) BETWEEN DATE '2025-11-10' AND DATE '2025-11-12'
GROUP BY o.start_zone
HAVING COUNT(*) >= 2
ORDER BY offers_count DESC, start_zone;

/* SQL Query 7 — Driver utilization (matches vs capacity)
 Purpose: For each driver, show confirmed riders carried and seats offered across their offers.
 Expected: driver, confirmed_riders, seats_offered, utilization%.
*/
SELECT u.full_name AS driver_name,
       COUNT(CASE WHEN m.status = 'confirmed' THEN 1 END) AS confirmed_riders,
       SUM(o.seats_available) AS seats_offered,
       CASE
         WHEN SUM(o.seats_available) = 0 THEN 0
         ELSE ROUND(
           100 * COUNT(CASE WHEN m.status = 'confirmed' THEN 1 END) 
               / SUM(o.seats_available), 1)
       END AS utilization_pct
FROM Users u
JOIN RideOffers o ON o.driver_id = u.user_id
LEFT JOIN Matches m ON m.offer_id = o.offer_id
GROUP BY u.user_id, u.full_name
ORDER BY utilization_pct DESC, driver_name;

/* SQL Query 8 — Suspended users with activity (UNION + filter)
 Purpose: List SUSPENDED users who still appear as a driver in any offer or as a rider in any request.
 Expected: user, role, where_seen.
*/
SELECT DISTINCT u.full_name, u.status, 'driver_in_offers' AS where_seen
FROM Users u
JOIN RideOffers o ON o.driver_id = u.user_id
WHERE u.status = 'SUSPENDED'
UNION
SELECT DISTINCT u.full_name, u.status, 'rider_in_requests' AS where_seen
FROM Users u
JOIN RideRequests q ON q.rider_id = u.user_id
WHERE u.status = 'SUSPENDED';

/* SQL Query 9 — Drivers with offers on 2025-11-10 + their avg rating (3 tables)
 Purpose: For drivers who had an offer on Nov 10, show their average rating (if any).
 Expected: driver, offers_on_day, avg_score (nullable).
*/
SELECT u.full_name AS driver_name,
       COUNT(*) AS offers_on_2025_11_10,
       ROUND(AVG(t.score), 2) AS avg_rating
FROM Users u
JOIN RideOffers o ON o.driver_id = u.user_id
LEFT JOIN Ratings  t ON t.ratee_user_id = u.user_id
WHERE TRUNC(o.start_time) = DATE '2025-11-10'
GROUP BY u.user_id, u.full_name
ORDER BY offers_on_2025_11_10 DESC, NVL(AVG(t.score), 0) DESC;

/* SQL Query 10 — "Did the rider rate that driver?" (3 tables + aliasing)
 Purpose: Find rider/driver pairs where the rider later rated that driver for that ride day.
 Expected: rider, driver, ride_day, rating, comment.
*/
SELECT rusr.full_name AS rider_name,
       dusr.full_name AS driver_name,
       TRUNC(o.start_time) AS ride_day,
       t.score,
       t.review_comment  -- Changed from comment to review_comment
FROM Matches m
JOIN RideOffers   o    ON m.offer_id   = o.offer_id
JOIN RideRequests q    ON m.request_id = q.request_id
JOIN Users dusr        ON o.driver_id  = dusr.user_id
JOIN Users rusr        ON q.rider_id   = rusr.user_id
JOIN Ratings t         ON t.rater_user_id = rusr.user_id
                       AND t.ratee_user_id = dusr.user_id
                       AND t.ride_date = TRUNC(o.start_time)
WHERE m.status IN ('confirmed','completed')
ORDER BY ride_day, driver_name, rider_name;