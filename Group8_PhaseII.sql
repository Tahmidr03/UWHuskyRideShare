/* Drop in dependency order (safe re-runs) */
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE Ratings CASCADE CONSTRAINTS';
  EXECUTE IMMEDIATE 'DROP TABLE Matches CASCADE CONSTRAINTS';
  EXECUTE IMMEDIATE 'DROP TABLE RideRequests CASCADE CONSTRAINTS';
  EXECUTE IMMEDIATE 'DROP TABLE RideOffers CASCADE CONSTRAINTS';
  EXECUTE IMMEDIATE 'DROP TABLE Vehicles CASCADE CONSTRAINTS';
  EXECUTE IMMEDIATE 'DROP TABLE Users CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL; 
END;
