/* ============ USERS ============ */
CREATE TABLE Users (
  user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uw_email   VARCHAR2(120) NOT NULL UNIQUE,
  full_name  VARCHAR2(80)  NOT NULL,
  role       VARCHAR2(10)  DEFAULT 'rider'   NOT NULL
             CHECK (role IN ('rider','driver','both')),
  status     VARCHAR2(10)  DEFAULT 'ACTIVE'  NOT NULL
             CHECK (status IN ('ACTIVE','SUSPENDED')),
  created_at DATE          DEFAULT SYSDATE   NOT NULL
);

/* ============ VEHICLES ============ */
CREATE TABLE Vehicles (
  vehicle_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id  NUMBER,  -- nullable; if driver deleted we keep record but null the link
  make       VARCHAR2(40) NOT NULL,
  model      VARCHAR2(40) NOT NULL,
  color      VARCHAR2(20),
  plate      VARCHAR2(15) UNIQUE,
  capacity   NUMBER(2) DEFAULT 4 NOT NULL
             CHECK (capacity BETWEEN 1 AND 7),
  CONSTRAINT fk_vehicle_driver
    FOREIGN KEY (driver_id) REFERENCES Users(user_id) ON DELETE SET NULL
);

/* ============ RIDE OFFERS ============ */
CREATE TABLE RideOffers (
  offer_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id       NUMBER NOT NULL,
  vehicle_id      NUMBER,
  start_zone      VARCHAR2(40) NOT NULL,  -- e.g., 'Kent P&R'
  end_zone        VARCHAR2(40) NOT NULL,  -- e.g., 'UW Tacoma'
  start_time      DATE         NOT NULL,
  seats_available NUMBER(2)    DEFAULT 3 NOT NULL
                  CHECK (seats_available BETWEEN 0 AND 7),
  notes           VARCHAR2(200),
  CONSTRAINT fk_offer_driver
    FOREIGN KEY (driver_id)  REFERENCES Users(user_id)        ON DELETE CASCADE,
  CONSTRAINT fk_offer_vehicle
    FOREIGN KEY (vehicle_id) REFERENCES Vehicles(vehicle_id)  ON DELETE SET NULL
);

/* ============ RIDE REQUESTS ============ */
CREATE TABLE RideRequests (
  request_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rider_id      NUMBER      NOT NULL,
  from_zone     VARCHAR2(40) NOT NULL,
  to_zone       VARCHAR2(40) NOT NULL,
  desired_time  DATE         NOT NULL,
  seats_needed  NUMBER(2)    DEFAULT 1 NOT NULL
                CHECK (seats_needed BETWEEN 1 AND 4),
  status        VARCHAR2(12) DEFAULT 'open' NOT NULL
                CHECK (status IN ('open','matched','cancelled','completed')),
  CONSTRAINT fk_request_rider
    FOREIGN KEY (rider_id) REFERENCES Users(user_id) ON DELETE CASCADE
);

/* ============ MATCHES (offer↔request) ============ */
CREATE TABLE Matches (
  match_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id   NUMBER NOT NULL,
  request_id NUMBER NOT NULL,
  matched_at DATE   DEFAULT SYSDATE NOT NULL,
  status     VARCHAR2(12) DEFAULT 'pending' NOT NULL
             CHECK (status IN ('pending','confirmed','completed','cancelled')),
  CONSTRAINT uq_offer_request UNIQUE (offer_id, request_id),
  CONSTRAINT fk_match_offer
    FOREIGN KEY (offer_id)   REFERENCES RideOffers(offer_id)     ON DELETE CASCADE,
  CONSTRAINT fk_match_request
    FOREIGN KEY (request_id) REFERENCES RideRequests(request_id) ON DELETE CASCADE
);

/* ============ RATINGS ============ */
CREATE TABLE Ratings (
  rating_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rater_user_id  NUMBER NOT NULL,
  ratee_user_id  NUMBER NOT NULL,
  ride_date      DATE   NOT NULL,
  score          NUMBER(1) NOT NULL CHECK (score BETWEEN 1 AND 5),
  review_comment VARCHAR2(400),  -- Changed from 'comment' to avoid reserved word
  created_at     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT fk_rating_rater
    FOREIGN KEY (rater_user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_rating_ratee
    FOREIGN KEY (ratee_user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
  CONSTRAINT chk_rater_ratee CHECK (rater_user_id <> ratee_user_id)
);

/* Helpful indexes */
CREATE INDEX ix_offer_start_time     ON RideOffers(start_time);
CREATE INDEX ix_request_desired_time ON RideRequests(desired_time);
CREATE INDEX ix_ratings_ratee        ON Ratings(ratee_user_id);

COMMIT;

